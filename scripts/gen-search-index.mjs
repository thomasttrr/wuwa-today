// Generates lib/search-index.ts — the slim ⌘K palette index.
// The palette only needs label/hint/href per entry; importing the full
// character records shipped ~680 KB of JSON as JS on every page.
// Run: node scripts/gen-search-index.mjs  (after data changes)
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => JSON.parse(readFileSync(join(root, p), "utf8"));

// Character order follows the import order in lib/characters.ts.
const libSrc = readFileSync(join(root, "lib/characters.ts"), "utf8");
const slugs = [...libSrc.matchAll(/data\/characters\/([a-z0-9-]+)\.json/g)].map((m) => m[1]);
const entries = [];
for (const slug of slugs) {
  const c = read(`data/characters/${slug}.json`);
  entries.push({
    label: c.name,
    hint: `Character · ${c.profile.element}`,
    href: `/characters/${c.slug}`,
  });
}
for (const g of read("data/prefarm.json").guides) {
  entries.push({ label: `${g.character} pre-farm`, hint: "Pre-farm guide", href: `/pre-farm/${g.slug}` });
}
for (const c of read("data/codes.json").active) {
  entries.push({ label: c.code, hint: "Redeem code · copy on the Today page", href: "/" });
}

const out = `// GENERATED by scripts/gen-search-index.mjs — do not edit by hand.
// Slim search index for the ⌘K palette (label/hint/href only), lazy-loaded
// on first open so the full character records stay off every page.
export interface SearchEntry { label: string; hint: string; href: string }
export const SEARCH_ENTRIES: SearchEntry[] = ${JSON.stringify(entries, null, 2)};
`;
writeFileSync(join(root, "lib/search-index.ts"), out);
console.log(`wrote lib/search-index.ts with ${entries.length} entries`);
